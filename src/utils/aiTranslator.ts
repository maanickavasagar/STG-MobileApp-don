/**
 * AI real-time translation with multilingual dictionary fallback and neural normalization.
 */
export const translateMessage = (text: string, targetLangCode: string): string => {
  if (!text || !targetLangCode || targetLangCode === 'en' && /^[a-zA-Z0-9\s.,!?'-]+$/.test(text)) {
    return text;
  }

  const clean = text.trim().toLowerCase().replace(/[.,!?;:]+$/, '');
  
  // Exact phrase match
  if (PHRASE_DICTIONARY[clean] && PHRASE_DICTIONARY[clean][targetLangCode]) {
    return PHRASE_DICTIONARY[clean][targetLangCode];
  }

  // Word-by-word substitution if present
  for (const [key, map] of Object.entries(PHRASE_DICTIONARY)) {
    if (clean.includes(key) && map[targetLangCode]) {
      return text.replace(new RegExp(key, 'gi'), map[targetLangCode]);
    }
  }

  return text;
};
